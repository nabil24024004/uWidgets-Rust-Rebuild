impl<'a> PathScanner<'a> {
    fn new(s: &'a str) -> Self {
        Self {
            bytes: s.as_bytes(),
            pos: 0,
        }
    }

    fn skip_ws_comma(&mut self) {
        while self.pos < self.bytes.len() {
            let b = self.bytes[self.pos];
            if b.is_ascii_whitespace() || b == b',' {
                self.pos += 1;
            } else {
                break;
            }
        }
    }

    fn peek_cmd(&mut self) -> Option<u8> {
        self.skip_ws_comma();
        let b = *self.bytes.get(self.pos)?;
        if b.is_ascii_alphabetic() {
            Some(b)
        } else {
            None
        }
    }

    fn next_number(&mut self) -> Option<f32> {
        self.skip_ws_comma();
        let start = self.pos;
        if self.pos < self.bytes.len() && matches!(self.bytes[self.pos], b'+' | b'-') {
            self.pos += 1;
        }
        let mut seen_digit = false;
        while self.pos < self.bytes.len() && self.bytes[self.pos].is_ascii_digit() {
            seen_digit = true;
            self.pos += 1;
        }
        if self.pos < self.bytes.len() && self.bytes[self.pos] == b'.' {
            self.pos += 1;
            while self.pos < self.bytes.len() && self.bytes[self.pos].is_ascii_digit() {
                seen_digit = true;
                self.pos += 1;
            }
        }
        if !seen_digit {
            self.pos = start;
            return None;
        }
        if self.pos < self.bytes.len() && matches!(self.bytes[self.pos], b'e' | b'E') {
            let exp_start = self.pos;
            self.pos += 1;
            if self.pos < self.bytes.len() && matches!(self.bytes[self.pos], b'+' | b'-') {
                self.pos += 1;
            }
            let mut exp_digits = false;
            while self.pos < self.bytes.len() && self.bytes[self.pos].is_ascii_digit() {
                exp_digits = true;
                self.pos += 1;
            }
            if !exp_digits {
                self.pos = exp_start;
            }
        }
        std::str::from_utf8(&self.bytes[start..self.pos])
            .ok()?
            .parse::<f32>()
            .ok()
    }

    fn next_flag(&mut self) -> Option<bool> {
        self.skip_ws_comma();
        let b = *self.bytes.get(self.pos)?;
        if b == b'0' {
            self.pos += 1;
            Some(false)
        } else if b == b'1' {
            self.pos += 1;
            Some(true)
        } else {
            None
        }
    }
}

/// Parses an SVG path string into a Direct2D `ID2D1PathGeometry`.
pub fn parse_svg_path(
    factory: &ID2D1Factory1,
    data: &str,
) -> windows_core::Result<ID2D1PathGeometry> {
    let geom = unsafe { factory.CreatePathGeometry()? };
    let sink = unsafe { geom.Open()? };
    unsafe { sink.SetFillMode(D2D1_FILL_MODE_WINDING) };

    let mut sc = PathScanner::new(data);
    let mut cmd: u8 = 0;
    let mut in_figure = false;
    let mut cur = D2D_POINT_2F { x: 0.0, y: 0.0 };
    let mut fig_start = cur;
    let mut last_cubic_ctrl: Option<D2D_POINT_2F> = None;
    let mut last_quad_ctrl: Option<D2D_POINT_2F> = None;

    loop {
        if let Some(c) = sc.peek_cmd() {
            sc.pos += 1;
            cmd = c;
        } else {
            sc.skip_ws_comma();
            if sc.pos >= sc.bytes.len() || cmd == 0 {
                break;
            }
            if cmd == b'M' {
                cmd = b'L';
            } else if cmd == b'm' {
                cmd = b'l';
            }
        }

        match cmd {
            b'M' | b'm' => {
                let (Some(x), Some(y)) = (sc.next_number(), sc.next_number()) else {
                    break;
                };
                if in_figure {
                    unsafe { sink.EndFigure(D2D1_FIGURE_END_OPEN) };
                }
                let pt = if cmd == b'm' {
                    D2D_POINT_2F {
                        x: cur.x + x,
                        y: cur.y + y,
                    }
                } else {
                    D2D_POINT_2F { x, y }
                };
                unsafe { sink.BeginFigure(pt, D2D1_FIGURE_BEGIN_FILLED) };
                in_figure = true;
                cur = pt;
                fig_start = pt;
                last_cubic_ctrl = None;
                last_quad_ctrl = None;
                cmd = if cmd == b'M' { b'L' } else { b'l' };
            }
            b'L' | b'l' => {
                let (Some(x), Some(y)) = (sc.next_number(), sc.next_number()) else {
                    break;
                };
                let pt = if cmd == b'l' {
                    D2D_POINT_2F {
                        x: cur.x + x,
                        y: cur.y + y,
                    }
                } else {
                    D2D_POINT_2F { x, y }
                };
                if !in_figure {
                    unsafe { sink.BeginFigure(cur, D2D1_FIGURE_BEGIN_FILLED) };
                    in_figure = true;
                }
                unsafe { sink.AddLine(pt) };
                cur = pt;
                last_cubic_ctrl = None;
                last_quad_ctrl = None;
            }
            b'H' | b'h' => {
                let Some(x) = sc.next_number() else { break };
                let pt = D2D_POINT_2F {
                    x: if cmd == b'h' { cur.x + x } else { x },
                    y: cur.y,
                };
                if in_figure {
                    unsafe { sink.AddLine(pt) };
                }
                cur = pt;
                last_cubic_ctrl = None;
                last_quad_ctrl = None;
            }
            b'V' | b'v' => {
                let Some(y) = sc.next_number() else { break };
                let pt = D2D_POINT_2F {
                    x: cur.x,
                    y: if cmd == b'v' { cur.y + y } else { y },
                };
                if in_figure {
                    unsafe { sink.AddLine(pt) };
                }
                cur = pt;
                last_cubic_ctrl = None;
                last_quad_ctrl = None;
            }
            b'C' | b'c' => {
                let (Some(x1), Some(y1), Some(x2), Some(y2), Some(x), Some(y)) = (
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                ) else {
                    break;
                };
                let rel = cmd == b'c';
                let (p1, p2, p3) = if rel {
                    (
                        D2D_POINT_2F {
                            x: cur.x + x1,
                            y: cur.y + y1,
                        },
                        D2D_POINT_2F {
                            x: cur.x + x2,
                            y: cur.y + y2,
                        },
                        D2D_POINT_2F {
                            x: cur.x + x,
                            y: cur.y + y,
                        },
                    )
                } else {
                    (
                        D2D_POINT_2F { x: x1, y: y1 },
                        D2D_POINT_2F { x: x2, y: y2 },
                        D2D_POINT_2F { x, y },
                    )
                };
                if in_figure {
                    unsafe {
                        sink.AddBezier(&D2D1_BEZIER_SEGMENT {
                            point1: p1,
                            point2: p2,
                            point3: p3,
                        });
                    }
                }
                cur = p3;
                last_cubic_ctrl = Some(p2);
                last_quad_ctrl = None;
            }
            b'S' | b's' => {
                let (Some(x2), Some(y2), Some(x), Some(y)) = (
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                ) else {
                    break;
                };
                let p1 = match last_cubic_ctrl {
                    Some(prev) => D2D_POINT_2F {
                        x: 2.0 * cur.x - prev.x,
                        y: 2.0 * cur.y - prev.y,
                    },
                    None => cur,
                };
                let rel = cmd == b's';
                let (p2, p3) = if rel {
                    (
                        D2D_POINT_2F {
                            x: cur.x + x2,
                            y: cur.y + y2,
                        },
                        D2D_POINT_2F {
                            x: cur.x + x,
                            y: cur.y + y,
                        },
                    )
                } else {
                    (D2D_POINT_2F { x: x2, y: y2 }, D2D_POINT_2F { x, y })
                };
                if in_figure {
                    unsafe {
                        sink.AddBezier(&D2D1_BEZIER_SEGMENT {
                            point1: p1,
                            point2: p2,
                            point3: p3,
                        });
                    }
                }
                cur = p3;
                last_cubic_ctrl = Some(p2);
                last_quad_ctrl = None;
            }
            b'Q' | b'q' => {
                let (Some(qx), Some(qy), Some(x), Some(y)) = (
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                ) else {
                    break;
                };
                let rel = cmd == b'q';
                let (qp, end) = if rel {
                    (
                        D2D_POINT_2F {
                            x: cur.x + qx,
                            y: cur.y + qy,
                        },
                        D2D_POINT_2F {
                            x: cur.x + x,
                            y: cur.y + y,
                        },
                    )
                } else {
                    (D2D_POINT_2F { x: qx, y: qy }, D2D_POINT_2F { x, y })
                };
                // Convert quadratic Bezier to cubic Bezier
                let c1 = D2D_POINT_2F {
                    x: cur.x + (2.0 / 3.0) * (qp.x - cur.x),
                    y: cur.y + (2.0 / 3.0) * (qp.y - cur.y),
                };
                let c2 = D2D_POINT_2F {
                    x: end.x + (2.0 / 3.0) * (qp.x - end.x),
                    y: end.y + (2.0 / 3.0) * (qp.y - end.y),
                };
                if in_figure {
                    unsafe {
                        sink.AddBezier(&D2D1_BEZIER_SEGMENT {
                            point1: c1,
                            point2: c2,
                            point3: end,
                        });
                    }
                }
                cur = end;
                last_quad_ctrl = Some(qp);
                last_cubic_ctrl = None;
            }
            b'T' | b't' => {
                let (Some(x), Some(y)) = (sc.next_number(), sc.next_number()) else {
                    break;
                };
                let qp = match last_quad_ctrl {
                    Some(prev) => D2D_POINT_2F {
                        x: 2.0 * cur.x - prev.x,
                        y: 2.0 * cur.y - prev.y,
                    },
                    None => cur,
                };
                let end = if cmd == b't' {
                    D2D_POINT_2F {
                        x: cur.x + x,
                        y: cur.y + y,
                    }
                } else {
                    D2D_POINT_2F { x, y }
                };
                let c1 = D2D_POINT_2F {
                    x: cur.x + (2.0 / 3.0) * (qp.x - cur.x),
                    y: cur.y + (2.0 / 3.0) * (qp.y - cur.y),
                };
                let c2 = D2D_POINT_2F {
                    x: end.x + (2.0 / 3.0) * (qp.x - end.x),
                    y: end.y + (2.0 / 3.0) * (qp.y - end.y),
                };
                if in_figure {
                    unsafe {
                        sink.AddBezier(&D2D1_BEZIER_SEGMENT {
                            point1: c1,
                            point2: c2,
                            point3: end,
                        });
                    }
                }
                cur = end;
                last_quad_ctrl = Some(qp);
                last_cubic_ctrl = None;
            }
            b'A' | b'a' => {
                let (Some(rx), Some(ry), Some(rot), Some(large_arc), Some(sweep), Some(x), Some(y)) = (
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_number(),
                    sc.next_flag(),
                    sc.next_flag(),
                    sc.next_number(),
                    sc.next_number(),
                ) else {
                    break;
                };
                let end = if cmd == b'a' {
                    D2D_POINT_2F {
                        x: cur.x + x,
                        y: cur.y + y,
                    }
                } else {
                    D2D_POINT_2F { x, y }
                };
                if in_figure {
                    unsafe {
                        sink.AddArc(&D2D1_ARC_SEGMENT {
                            point: end,
                            size: D2D_SIZE_F {
                                width: rx.abs(),
                                height: ry.abs(),
                            },
                            rotationAngle: rot,
                            sweepDirection: if sweep {
                                D2D1_SWEEP_DIRECTION_CLOCKWISE
                            } else {
                                D2D1_SWEEP_DIRECTION_COUNTER_CLOCKWISE
                            },
                            arcSize: if large_arc {
                                D2D1_ARC_SIZE_LARGE
                            } else {
                                D2D1_ARC_SIZE_SMALL
                            },
                        });
                    }
                }
                cur = end;
                last_cubic_ctrl = None;
                last_quad_ctrl = None;
            }
            b'Z' | b'z' => {
                if in_figure {
                    unsafe { sink.EndFigure(D2D1_FIGURE_END_CLOSED) };
                    in_figure = false;
                }
                cur = fig_start;
                last_cubic_ctrl = None;
                last_quad_ctrl = None;
                cmd = 0;
            }
            _ => break,
        }
    }

    if in_figure {
        unsafe { sink.EndFigure(D2D1_FIGURE_END_OPEN) };
    }
    unsafe { sink.Close()? };
    Ok(geom.into())
}
